export const LANGUAGES = Object.freeze(['en', 'it', 'nl']);

export const LANGUAGE_OPTIONS = Object.freeze([
  Object.freeze({ value: 'en', label: 'English' }),
  Object.freeze({ value: 'it', label: 'Italiano' }),
  Object.freeze({ value: 'nl', label: 'Nederlands' }),
]);

export function normalizeLanguage(raw) {
  if (typeof raw !== 'string') return 'en';
  const code = raw.trim().toLowerCase().slice(0, 2);
  return LANGUAGES.includes(code) ? code : 'en';
}

export function detectDefaultLanguage(navLang) {
  if (typeof navLang === 'string') return normalizeLanguage(navLang);
  if (typeof navigator !== 'undefined' && typeof navigator.language === 'string') {
    return normalizeLanguage(navigator.language);
  }
  return 'en';
}

